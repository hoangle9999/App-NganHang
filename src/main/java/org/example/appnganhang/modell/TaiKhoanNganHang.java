package org.example.appnganhang.modell;

import java.math.BigDecimal;

public class TaiKhoanNganHang {
    private String maTaiKhoan;
    private String maKhachHang;
    private String soTaiKhoan;
    private BigDecimal soDu;
    private String trangThai;
    private String maChiNhanh;
    private String maHanMuc;

    public String getMaTaiKhoan() {
        return maTaiKhoan;
    }

    public void setMaTaiKhoan(String maTaiKhoan) {
        this.maTaiKhoan = maTaiKhoan;
    }

    public String getMaKhachHang() {
        return maKhachHang;
    }

    public void setMaKhachHang(String maKhachHang) {
        this.maKhachHang = maKhachHang;
    }

    public String getSoTaiKhoan() {
        return soTaiKhoan;
    }

    public void setSoTaiKhoan(String soTaiKhoan) {
        this.soTaiKhoan = soTaiKhoan;
    }

    public BigDecimal getSoDu() {
        return soDu;
    }

    public void setSoDu(BigDecimal soDu) {
        this.soDu = soDu;
    }

    public String getTrangThai() {
        return trangThai;
    }

    public void setTrangThai(String trangThai) {
        this.trangThai = trangThai;
    }

    public String getMaChiNhanh() {
        return maChiNhanh;
    }

    public void setMaChiNhanh(String maChiNhanh) {
        this.maChiNhanh = maChiNhanh;
    }

    public String getMaHanMuc() {
        return maHanMuc;
    }

    public void setMaHanMuc(String maHanMuc) {
        this.maHanMuc = maHanMuc;
    }
}
